import {chromium} from 'playwright-core'
import assert from 'node:assert/strict'
const [webOrigin,adminOrigin]=process.argv.slice(2)
const browser=await chromium.launch({executablePath:process.env.PAPR_PDF_BROWSER??'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true})
try {
 const page=await browser.newPage({viewport:{width:1400,height:900}}),errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto(adminOrigin)
 await page.getByLabel('用户名',{exact:true}).fill('owner')
 await page.getByLabel('密码',{exact:true}).fill('test-only-admin-password')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await page.getByRole('link',{name:'模板管理',exact:true}).click()
 await page.getByRole('button',{name:'配置模板',exact:true}).click()
 const node=page.getByLabel('规则1二级目录',{exact:true})
 assert.equal(await node.locator('option').count(),2)
 assert.ok(!(await node.innerText()).includes('没有关联组件的目录'))
 await page.getByLabel('规则1出题组件',{exact:true}).selectOption('g4_upper_angles_v1')
 await page.getByLabel('规则1题型',{exact:true}).selectOption('判断题')
 await page.getByLabel('规则2出题组件',{exact:true}).selectOption('g4_upper_statistics_v1')
 await page.getByLabel('规则2题型',{exact:true}).selectOption('应用题')
 await page.getByLabel('判断题每行题数',{exact:true}).selectOption('1')
 await page.getByLabel('应用题每行题数',{exact:true}).selectOption('1')
 await page.getByRole('button',{name:'组卷预览',exact:true}).click()
 await page.getByRole('button',{name:'生成样例题查看',exact:true}).click()
 await page.getByRole('link',{name:/打开PDF/}).waitFor({timeout:120000})
 const workspace=await page.evaluate(async()=> (await (await fetch('/admin/api/v2/workspace')).json()).data)
 const template=workspace.templates[0]
 assert.equal(workspace.components.length,14)
 assert.equal(template.columns_by_kind['判断题'],1)
 assert.equal(template.columns_by_kind['应用题'],1)
 const job=await page.evaluate(async id=>(await (await fetch('/admin/api/v2/jobs/'+id)).json()).data,template.preview_job.id)
 assert.deepEqual(job.document.questions.map(q=>q.question_type),[...Array(6).fill('judgment'),...Array(3).fill('application')])
 assert.ok(job.document.questions.some(q=>q.render_spec.diagram?.kind==='angle'))
 assert.equal(job.assets.length,2)
 await page.getByRole('button',{name:'运行自动验证',exact:true}).click()
 await page.getByLabel('审题意见',{exact:true}).fill('自动化布局验收，不代替正式人工审题')
 await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent==='审题通过'&&!b.disabled),{},{timeout:120000})
 await page.getByRole('button',{name:'审题通过',exact:true}).click()
 const publish=page.getByRole('button',{name:'发布模板',exact:true})
 await publish.click()
 const result=page.getByText('发布成功！模板已开放，用户端可选择此模板生成练习。',{exact:true})
 await result.waitFor()
 const box=await result.boundingBox();assert.ok(box&&box.y<900&&box.y+box.height>0,'发布成功提示应在当前视口可见')
 await page.goto(webOrigin)
 await page.getByRole('button',{name:'＋ 生成练习',exact:true}).click()
 await page.getByRole('button',{name:'选择模板',exact:true}).click()
 assert.ok((await page.locator('main').innerText()).includes('判断题每行 1 题'))
 assert.ok((await page.locator('main').innerText()).includes('应用题每行 1 题'))
 await page.getByRole('button',{name:'确认生成',exact:true}).click()
 await page.getByRole('button',{name:'查看练习',exact:true}).waitFor({timeout:120000})
 await page.getByRole('button',{name:'查看练习',exact:true}).click()
 const links=page.getByRole('link',{name:'打开／下载PDF',exact:true});await links.first().waitFor();assert.equal(await links.count(),2)
 const file=await links.first().getAttribute('href')
 const status=await page.evaluate(async url=>(await fetch(url)).status,file);assert.equal(status,200)
 assert.deepEqual(errors,[])
 console.log('PASS: 14 server components, judgment/application configuration, sample/validation/review/publish, actual user PDF download')
} finally {await browser.close()}
