import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { chromium } from 'playwright-core'
const [executablePath, , admin, output] = process.argv.slice(2)
const browser = await chromium.launch({ executablePath, headless: true })
const page = await browser.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(admin)
  await page.getByLabel('用户名', { exact: true }).fill('owner')
  await page.getByLabel('密码', { exact: true }).fill('test-only-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '资料来源', exact: true }).click()
  const sources = page.getByRole('region', { name: '资料来源维护', exact: true })
  await sources.getByLabel('资料标题', { exact: true }).fill('浏览器测试参考资料')
  await sources.getByLabel('参考说明', { exact: true }).fill('隔离数据，仅用于验证来源维护')
  await sources.getByLabel('资料变更理由', { exact: true }).fill('浏览器验收资料录入')
  await sources.getByRole('button', { name: '保存资料来源', exact: true }).click()
  await sources.getByText('资料来源已保存。', { exact: true }).waitFor()
  await page.getByRole('button', { name: '知识点与训练目标', exact: true }).click()
  const editor = page.getByRole('region', { name: '知识点与训练目标维护', exact: true })
  await editor.getByLabel('内容变更理由', { exact: true }).fill('隔离数据内容维护验收')
  await editor.getByLabel('知识点编码', { exact: true }).fill('BROWSER_POINT')
  await editor.getByLabel('知识点名称', { exact: true }).fill('浏览器知识点')
  await editor.getByLabel('知识点定义', { exact: true }).fill('测试整数乘法训练')
  await editor.getByLabel('知识边界', { exact: true }).fill('仅包含整数')
  await editor.getByLabel('资料来源', { exact: true }).selectOption({ label: '浏览器测试参考资料' })
  await editor.getByRole('button', { name: '保存知识点草稿', exact: true }).click()
  await editor.getByText('知识点草稿已保存，尚未发布。', { exact: true }).waitFor()
  assert.equal(await editor.getByRole('button', { name: '发布知识点修订', exact: true }).isDisabled(), true)
  await editor.getByLabel('目标编码', { exact: true }).fill('BROWSER_OBJECTIVE')
  await editor.getByLabel('目标名称', { exact: true }).fill('测试训练目标')
  await editor.getByLabel('目标范围', { exact: true }).fill('位值训练')
  await editor.getByLabel('达成标准（每行一项）', { exact: true }).fill('部分积正确\n位值对齐')
  await editor.getByRole('button', { name: '保存训练目标草稿', exact: true }).click()
  await editor.getByText('训练目标草稿已保存，尚未发布。', { exact: true }).waitFor()
  await editor.getByLabel('我已核对目标范围与达成标准', { exact: true }).check()
  const blocked = page.waitForResponse(r => r.request().method() === 'POST' && r.url().includes('/objective-revisions/') && r.url().endsWith('/publish'))
  await editor.getByRole('button', { name: '发布目标修订', exact: true }).click()
  assert.equal((await blocked).status(), 409)
  await editor.getByRole('alert').filter({ hasText: '请先发布同一知识点的关联修订' }).waitFor()
  await editor.getByLabel('我已核对知识点修订内容与边界', { exact: true }).check()
  await editor.getByRole('button', { name: '发布知识点修订', exact: true }).click()
  await editor.getByText('知识点修订已发布。目录映射和模板关联需按修订分别维护。', { exact: true }).waitFor()
  assert.equal(await editor.getByLabel('知识点名称', { exact: true }).isDisabled(), true)
  await editor.getByRole('button', { name: '维护目标BROWSER_OBJECTIVE', exact: true }).click()
  await editor.getByLabel('我已核对目标范围与达成标准', { exact: true }).check()
  await editor.getByRole('button', { name: '发布目标修订', exact: true }).click()
  await editor.getByText('训练目标修订已发布。', { exact: true }).waitFor()
  assert.equal(await editor.getByLabel('目标范围', { exact: true }).isDisabled(), true)
  await editor.getByRole('button', { name: '复制目标修订为新草稿', exact: true }).click()
  await editor.getByText('已复制训练目标新草稿。', { exact: true }).waitFor()
  await editor.getByLabel('目标范围', { exact: true }).fill('新的测试范围')
  await editor.getByRole('button', { name: '保存训练目标草稿', exact: true }).click()
  await editor.getByText('训练目标草稿已保存，尚未发布。', { exact: true }).waitFor()
  await editor.getByLabel('目标修订', { exact: true }).selectOption({ index: 1 })
  assert.equal(await editor.getByLabel('目标范围', { exact: true }).inputValue(), '位值训练')
  await editor.getByRole('button', { name: '复制知识点修订为新草稿', exact: true }).click()
  await editor.getByText('已复制知识点新草稿，原发布修订保持不变。', { exact: true }).waitFor()
  await editor.getByLabel('知识点定义', { exact: true }).fill('第二版整数训练定义')
  await editor.getByLabel('我已核对知识点修订内容与边界', { exact: true }).check()
  assert.equal(await editor.getByRole('button', { name: '发布知识点修订', exact: true }).isDisabled(), true)
  await editor.getByRole('button', { name: '保存知识点草稿', exact: true }).click()
  await editor.getByText('知识点草稿已保存，尚未发布。', { exact: true }).waitFor()
  await editor.getByLabel('知识点修订', { exact: true }).selectOption({ index: 1 })
  assert.equal(await editor.getByLabel('知识点定义', { exact: true }).inputValue(), '测试整数乘法训练')
  assert.equal(await editor.getByLabel('知识点定义', { exact: true }).isDisabled(), true)
  await page.screenshot({ path: output + '/knowledge-manager.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ status: 'knowledge_maintenance_passed', immutable_published: true, publication_order: true }))
} catch (error) {
  await page.screenshot({ path: output + '/knowledge-failure.png', fullPage: true })
  await writeFile(output + '/knowledge-failure-aria.txt', await page.locator('main').ariaSnapshot())
  throw error
} finally {
  await browser.close()
}
