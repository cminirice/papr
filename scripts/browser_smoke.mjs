// Invoked only by the opt-in pytest fixture, against isolated test servers/data.
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { chromium } from 'playwright-core'

const [executablePath, web, admin, output] = process.argv.slice(2)
const browser = await chromium.launch({ executablePath, headless: true })
const errors = []
try {
  const context = await browser.newContext({ timezoneId: 'America/Los_Angeles', acceptDownloads: true })
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(web)
  await page.getByRole('link', { name: '历史练习', exact: true }).click()
  await page.getByText('暂无已完成的练习。', { exact: false }).waitFor()
  await page.getByRole('link', { name: '开始练习', exact: true }).click()
  await page.getByLabel(/^目录/).selectOption({ index: 1 })
  await page.getByLabel(/^主题/).selectOption({ index: 1 })
  await page.getByRole('checkbox').first().check()
  await page.getByRole('button', { name: '查看可用题量' }).click()
  await page.getByLabel(/^解答题/).selectOption('3')
  await page.getByRole('button', { name: '生成练习', exact: true }).click()
  await page.getByRole('button', { name: '打开练习', exact: true }).click({ timeout: 90000 })
  await page.getByRole('link', { name: '下载PDF' }).first().waitFor()
  assert.match(await page.locator('main').innerText(), /2030\/01\/01|2030-01-01|2030年1月1日/)
  const session = await (await context.request.get(web + '/api/v1/session')).json()
  assert.equal(session.data.can_generate, false)
  const before = session.data.next_generation_at
  const preview = page.getByRole('region', { name: '试卷预览' })
  assert.equal(await preview.locator('.question-heading').count(), 3)
  assert.equal(await preview.locator('ol').count(), 0)
  await preview.getByLabel('显示答案与解析').check()
  assert.equal(await preview.locator('ol').count(), 3)
  await preview.getByLabel('显示答案与解析').uncheck()
  assert.equal(await preview.locator('ol').count(), 0)
  let submissions = 0
  page.on('request', request => {
    if (request.method() === 'POST' && request.url().endsWith('/api/v1/paper-jobs')) submissions++
  })
  // Change the form first so reuse must actually restore the saved selection.
  await page.getByLabel(/^难度/).selectOption('standard')
  await preview.getByRole('button', { name: '沿用配置再练一份' }).click()
  await page.getByText('已沿用原目录、知识点、难度和题量，并检查当前可用性。确认后点击“生成练习”创建新题。', { exact: true }).waitFor()
  assert.equal(await page.getByLabel(/^难度/).inputValue(), 'basic')
  assert.equal(await page.getByLabel(/^解答题/).inputValue(), '3')
  assert.equal(submissions, 0)
  const links = page.getByRole('link', { name: '下载PDF', exact: true })
  assert.equal(await links.count(), 2)
  for (let i = 0; i < 2; i++) {
    const pending = page.waitForEvent('download')
    await links.nth(i).click()
    const download = await pending
    const path = output + `/browser-download-${i}.pdf`
    await download.saveAs(path)
    assert.equal((await readFile(path)).subarray(0, 5).toString(), '%PDF-')
  }
  const inline = await page.getByRole('link', { name: '打开并打印' }).first().getAttribute('href')
  const response = await context.request.get(web + inline)
  assert.equal(response.status(), 200)
  assert.match(response.headers()['content-disposition'], /inline/)
  await page.getByRole('button', { name: '生成练习', exact: true }).click()
  await page.getByText('下次可生成时间：', { exact: false }).waitFor()
  assert.equal(submissions, 1)
  assert.equal((await (await context.request.get(web + '/api/v1/session')).json()).data.next_generation_at, before)
  await page.screenshot({ path: output + '/user.png', fullPage: true })
  // Closing pages/context and restoring persistent cookies keeps the same history.
  const state = await context.storageState()
  await context.close()
  const restored = await browser.newContext({ storageState: state })
  const history = await restored.newPage()
  history.on('pageerror', error => errors.push(error.message))
  await history.goto(web)
  await history.getByRole('button', { name: '打开练习', exact: true }).click()
  await history.getByRole('link', { name: '下载PDF' }).first().waitFor()
  assert.equal(await history.getByRole('region', { name: '试卷预览' }).locator('.question-heading').count(), 3)
  await history.getByRole('link', { name: '历史练习', exact: true }).click()
  const records = history.getByRole('region', { name: '历史练习', exact: true })
  await records.getByText('共 3 题：选择 0 题，填空 0 题，解答 3 题', { exact: true }).waitFor()
  assert.equal(await records.locator('article[data-paper-id]').count(), 1)
  await history.reload()
  await records.getByRole('button', { name: '查看练习', exact: true }).click()
  await records.getByRole('link', { name: '下载PDF' }).first().waitFor()
  await records.getByRole('button', { name: '沿用配置再练一份' }).click()
  await history.getByText('已沿用原目录、知识点、难度和题量，并检查当前可用性。确认后点击“生成练习”创建新题。', { exact: true }).waitFor()
  assert.equal(await history.getByLabel(/^解答题/).inputValue(), '3')
  await history.goBack()
  await records.getByRole('button', { name: '查看练习', exact: true }).waitFor()
  await records.getByRole('link', { name: '查看生成任务' }).click()
  await history.getByRole('heading', { name: '本浏览器的任务与历史练习' }).waitFor()
  // UI-only edge cases use controlled responses; real API pagination is covered in pytest.
  const saved = (await (await restored.request.get(web + '/api/v1/papers')).json()).data.items[0]
  let expired = false
  let requestedCursor = null
  await history.route('**/api/v1/papers?*', async route => {
    if (expired) return route.fulfill({ status: 401, json: { error: { code: 'SESSION_EXPIRED', message: '会话已失效' } } })
    requestedCursor = new URL(route.request().url()).searchParams.get('cursor')
    const data = requestedCursor
      ? { items: [saved, { ...saved, id: '00000000-0000-4000-8000-000000000001' }], next_cursor: null, has_more: false }
      : { items: [saved], next_cursor: 'test-next-page', has_more: true }
    await route.fulfill({ json: { data } })
  })
  await history.getByRole('link', { name: '历史练习', exact: true }).click()
  await records.getByRole('button', { name: '查看更多练习', exact: true }).click()
  await records.getByText('已显示全部历史练习。', { exact: true }).waitFor()
  assert.equal(requestedCursor, 'test-next-page')
  assert.equal(await records.locator('article[data-paper-id]').count(), 2)
  expired = true
  await records.getByRole('button', { name: '刷新历史', exact: true }).click()
  await records.getByRole('alert').filter({ hasText: '浏览器会话已失效' }).waitFor()
  assert.equal(await records.locator('article[data-paper-id]').count(), 0)
  await history.unroute('**/api/v1/papers?*')
  const stranger = await browser.newContext()
  assert.equal((await stranger.request.get(web + inline)).status(), 401)
  const adminPage = await restored.newPage()
  adminPage.on('pageerror', error => errors.push(error.message))
  await adminPage.goto(admin)
  await adminPage.getByLabel('用户名', { exact: true }).fill('owner')
  await adminPage.getByLabel('密码', { exact: true }).fill('test-only-admin-password')
  await adminPage.getByRole('button', { name: '登录', exact: true }).click()
  await adminPage.getByRole('button', { name: '查看配置', exact: true }).first().click()
  await adminPage.getByRole('button', { name: '复制为新草稿' }).click()
  await adminPage.getByText('已复制为新草稿，需要重新验证和审题。', { exact: true }).waitFor()
  await adminPage.getByLabel(/^题目每行题数/).first().selectOption('5')
  await adminPage.getByLabel(/^解析每行题数/).first().selectOption('3')
  await adminPage.getByRole('button', { name: '保存草稿', exact: true }).click()
  await adminPage.getByText('草稿已保存。已有有效题量已清空，后续须重新验证和审题。', { exact: true }).waitFor()
  await adminPage.getByRole('button', { name: '重新加载（放弃未保存修改）' }).click()
  await adminPage.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent.trim() === '保存草稿' && !b.disabled))
  assert.equal(await adminPage.getByLabel(/^题目每行题数/).first().inputValue(), '5')
  assert.equal(await adminPage.getByLabel(/^解析每行题数/).first().inputValue(), '3')
  await adminPage.screenshot({ path: output + '/admin.png', fullPage: true })
  await adminPage.getByRole('button', { name: '生成记录与统计', exact: true }).click()
  await adminPage.getByRole('button', { name: '查看任务', exact: true }).waitFor()
  const successful = adminPage.locator('.totals div').filter({ has: adminPage.locator('dt', { hasText: '成功出卷' }) })
  assert.equal(await successful.locator('dd').innerText(), '1')
  await adminPage.getByLabel(/^任务状态/).selectOption('failed')
  await adminPage.getByRole('button', { name: '查询记录与统计', exact: true }).click()
  await adminPage.getByText('此条件下暂无任务。', { exact: true }).waitFor()
  assert.equal(await successful.locator('dd').innerText(), '1')
  await adminPage.getByLabel(/^任务状态/).selectOption('succeeded')
  await adminPage.getByRole('button', { name: '查询记录与统计', exact: true }).click()
  await adminPage.getByRole('button', { name: '查看任务', exact: true }).click()
  await adminPage.getByRole('heading', { name: '已保存的题目快照' }).waitFor()
  await adminPage.screenshot({ path: output + '/operations.png', fullPage: true })
  await adminPage.getByRole('button', { name: '查看来源模板版本', exact: true }).click()
  await adminPage.getByText('此版本当前不可编辑。', { exact: true }).waitFor()
  assert.match(await adminPage.getByLabel(/^版本/).locator('option:checked').innerText(), /第1版/)
  await adminPage.getByRole('button', { name: '退出登录' }).click()
  await adminPage.getByRole('button', { name: '登录', exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ status: 'browser_flow_passed', downloads: 2, history_restored: true,
    cooldown: true, preview_answers: true, reuse_selection: true, admin_columns_saved: [5, 3], page_errors: errors }))
} finally {
  await browser.close()
}
