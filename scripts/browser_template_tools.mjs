import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { chromium } from 'playwright-core'
const [executablePath, , admin, output] = process.argv.slice(2)
const browser = await chromium.launch({ executablePath, headless: true })
const page = await browser.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(admin)
  await page.getByLabel('用户名', { exact: true }).fill('owner')
  await page.getByLabel('密码', { exact: true }).fill('test-only-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '新建模板', exact: true }).click()
  const creator = page.getByRole('region', { name: '新建模板', exact: true })
  await creator.getByLabel('新模板编码', { exact: true }).fill('BROWSER_TEMPLATE_TOOLS')
  await creator.getByLabel('新模板名称', { exact: true }).fill('浏览器新建乘法模板')
  if (process.env.PAPR_TEST_TEMPLATE_TASK) await creator.getByLabel('训练内容', { exact: true }).selectOption(process.env.PAPR_TEST_TEMPLATE_TASK)
  if (process.env.PAPR_TEST_TEMPLATE_TYPE && !process.env.PAPR_TEST_TEMPLATE_TASK) await creator.getByLabel('模板题型', { exact: true }).selectOption(process.env.PAPR_TEST_TEMPLATE_TYPE)
  await creator.getByLabel('新建模板理由', { exact: true }).fill('隔离数据模板工具验收')
  await creator.getByRole('button', { name: '创建模板草稿', exact: true }).click()
  const preview = page.getByRole('region', { name: '草稿独立预览', exact: true })
  await preview.getByRole('button', { name: '生成草稿预览', exact: true }).click()
  await preview.getByRole('heading', { name: /^预览完成/ }).waitFor({ timeout: 60000 })
  assert.equal(await preview.locator('.question-heading').count(), 3)
  const originalQuestions = await preview.locator('.question-heading').allTextContents()
  assert.equal(await preview.locator('ol').count(), 0)
  await preview.getByLabel('显示预览答案与解析', { exact: true }).check()
  assert.equal(await preview.locator('ol').count(), 3)
  await preview.getByLabel('显示预览答案与解析', { exact: true }).uncheck()
  await page.getByLabel(/^题目每行题数/).first().selectOption('3')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await page.getByText('草稿已保存。已有有效题量已清空，后续须重新验证和审题。', { exact: true }).waitFor()
  await preview.getByText('草稿或关联内容已变化，这是提交时的旧快照，请重新预览。', { exact: true }).waitFor()
  assert.deepEqual(await preview.locator('.question-heading').allTextContents(), originalQuestions)
  await preview.getByLabel('预览题数', { exact: true }).fill('4')
  await preview.getByLabel('预览种子', { exact: true }).fill('different-preview')
  await preview.getByRole('button', { name: '生成草稿预览', exact: true }).click()
  await preview.locator('.question-heading').nth(6).waitFor({ timeout: 60000 })
  assert.equal(await preview.locator('.preview-job').count(), 2)
  assert.match(await preview.locator('.preview-job').first().locator('.question-row').first().getAttribute('style'), /repeat\(3,/)
  const overview = page.getByRole('region', { name: '候选目录与模板', exact: true })
  await overview.getByLabel('模板名称或编码', { exact: true }).fill('BROWSER_TEMPLATE_TOOLS')
  await overview.getByLabel('模板发布情况', { exact: true }).selectOption('true')
  await overview.getByRole('button', { name: '筛选模板', exact: true }).click()
  await overview.getByRole('heading', { name: '模板（0）', exact: true }).waitFor()
  await overview.getByLabel('模板发布情况', { exact: true }).selectOption('false')
  await overview.getByRole('button', { name: '筛选模板', exact: true }).click()
  await overview.getByRole('heading', { name: '模板（1）', exact: true }).waitFor()
  await overview.getByRole('button', { name: '查看配置', exact: true }).click()
  await preview.locator('.question-heading').nth(6).waitFor()
  await page.screenshot({ path: output + '/template-tools.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ status: 'template_tools_passed', new_template: true, previews: 2, stale_snapshot: true, filters: true }))
} catch (error) {
  await page.screenshot({ path: output + '/template-tools-failure.png', fullPage: true })
  await writeFile(output + '/template-tools-failure-aria.txt', await page.locator('main').ariaSnapshot())
  throw error
} finally {
  await browser.close()
}
